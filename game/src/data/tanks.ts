export function getTechTreeOrder(nation: NationId, includeExperimental: boolean = false, blueprintIds: string[] = []): string[] {
  const base = TECH_TREE_ORDER[nation] || [];
  const blueprints = BLUEPRINT_TANK_IDS.filter(id => TANKS[id].nation === nation && blueprintIds.includes(id));
  if (includeExperimental && EXPERIMENTAL_TANKS[nation]) {
    return [...base, ...blueprints, EXPERIMENTAL_TANKS[nation]];
  }
  return [...base, ...blueprints];
}

/**
 * Check if a tank can be researched / unlocked based on prerequisite tanks in the branching tree
 */
export function canUnlockTank(tankId: string, unlockedTankIds: string[], blueprintIds: string[] = []): boolean {
  if (unlockedTankIds.includes(tankId)) return true;
  const def = TANKS[tankId];
  if (!def) return false;
  if (def.blueprintCost && !blueprintIds.includes(tankId)) return false;
  // Starter tier 1 tanks with no prerequisites are always available
  if (!def.prerequisites || def.prerequisites.length === 0) return true;
  // Unlocking ANY prerequisite tank unlocks this branch option
  return def.prerequisites.some(prereqId => unlockedTankIds.includes(prereqId));
}
